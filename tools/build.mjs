import fs from 'node:fs';
const version=JSON.parse(fs.readFileSync('package.json','utf8')).version;
const modules = ['core','textures','animations','native_catalog','native','workflows','advanced','mailbox','plugin'].map(name => fs.readFileSync(`src/${name}.js`,'utf8').replace(/^if \(typeof module[^\n]+$/gm,''));
const code = `// Codex Blockbench Bridge ${version} — generated by tools/build.mjs\n(function () {\n"use strict";\n` + modules.join('\n') + '\n})();\n';
fs.mkdirSync('plugin',{recursive:true});
fs.writeFileSync('plugin/codex_blockbench_bridge.js',code);
fs.mkdirSync('skill/blockbench-modeling/assets',{recursive:true});
fs.writeFileSync('skill/blockbench-modeling/assets/codex_blockbench_bridge.js',code);
for(const file of fs.readdirSync('examples').filter(file=>file.endsWith('.json')))fs.copyFileSync(`examples/${file}`,`skill/blockbench-modeling/assets/${file}`);
console.log('Built plugin/codex_blockbench_bridge.js');
